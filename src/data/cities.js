const fallbackImage = "https://images.unsplash.com/photo-1566073771259-6a8506099945?w=900";

export const cityImage = (city) => {
  if (!city) return fallbackImage;
  if (city.image) return city.image;
  const best = bestTimeDestinations.find((d) => d.name === city.name);
  return best?.image || fallbackImage;
};

export const slugify = (name) =>
  String(name).trim().toLowerCase().replace(/\s+/g, "-");

export const findCity = (value) => {
  const q = String(value || "").trim().toLowerCase();
  if (!q) return null;
  return cities.find((c) => c.name.toLowerCase() === q || slugify(c.name) === q) || null;
};

export const cityLabel = (city) => `${city.name} (${city.region}, ${city.country})`;

const num = (text) => Number(String(text).replace(/[^\d]/g, "")) || 0;

const seasonal = [1.1, 1.0, 0.9, 0.85, 0.8, 0.75, 0.8, 0.85, 0.9, 1.0, 1.15, 1.3];

export const monthRange = (cityName, month) => {
  const best = bestTimeDestinations.find((d) => d.name === cityName);
  const row = best?.prices.find((p) => p[0] === month);
  if (row) return { low: num(row[1]), high: num(row[2]) };
  const city = findCity(cityName);
  const factor = seasonal[MONTHS.indexOf(month)] ?? 1;
  const avg = city?.avg || 5000;
  return { low: Math.round((avg * 0.35 * factor) / 5) * 5, high: Math.round((avg * 2.2 * factor) / 5) * 5 };
};

export const monthFactor = (cityName, month) => {
  if (!month) return 1;
  const best = bestTimeDestinations.find((d) => d.name === cityName);
  if (!best) return seasonal[MONTHS.indexOf(month)] ?? 1;
  const lows = best.prices.map((p) => num(p[1]));
  const avg = lows.reduce((a, b) => a + b, 0) / lows.length;
  const row = best.prices.find((p) => p[0] === month);
  return row && avg ? num(row[1]) / avg : 1;
};

export const monthStart = (month) => {
  const index = MONTHS.indexOf(month);
  if (index < 0) return null;
  const year = index < TODAY.getMonth() ? TODAY.getFullYear() + 1 : TODAY.getFullYear();
  return new Date(year, index, 1);
};

export const toISO = (date) => {
  if (!date) return "";
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
};

export const fromISO = (iso) => {
  if (!iso) return null;
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
};

export const searchUrl = ({ city, checkIn, checkOut, month, adults = 2, children = 0, rooms = 1 }) => {
  const p = new URLSearchParams();
  if (city) p.set("city", city);
  if (checkIn) p.set("checkIn", typeof checkIn === "string" ? checkIn : toISO(checkIn));
  if (checkOut) p.set("checkOut", typeof checkOut === "string" ? checkOut : toISO(checkOut));
  if (month && !checkIn) p.set("month", month);
  p.set("adults", String(adults));
  p.set("children", String(children));
  p.set("rooms", String(rooms));
  return `/hotels?${p.toString()}`;
};
